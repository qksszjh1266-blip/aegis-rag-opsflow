"""区分知识说明与操作请求，知识问句不消耗报修槽位追问轮数。"""

import re


def is_knowledge_question(message: str) -> bool:
    """显式提交或执行请求优先；流程、原因、条件与规格询问只读取知识。"""
    if re.search(r"(?:请|帮我|我要|立即|现在|麻烦)\s*(?:创建|提交|报修|派单|执行)", message):
        return False
    return bool(
        re.search(
            r"什么意思|是什么|为什么|怎么|如何|多少|多久|什么时候|能不能|是否|支持吗|"
        r"有什么|哪款|哪个|哪些|流程|规则|含义|步骤|参数|规格|条件|阈值|"
        r"查询|查下|查阅|列出|告诉|说明|解释|介绍|发我",
            message,
        )
    )
